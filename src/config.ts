/**
 * Все настраиваемые константы игры. Единицы: ячейки мира и секунды.
 *
 * Менять числа только здесь. Соотношения между ними, помеченные ниже как
 * инварианты, — не вкусовые: их нарушение ломает механику молча.
 *
 * Величина в ячейках принадлежит одному из трёх семейств, и семейство —
 * свойство самой величины (требование `game-shell`, «Игровые величины
 * калиброваны по опорному кадру»):
 *
 * 1. ДЛИНА — соразмерна кадру: скорости, ускорения, дальности, радиусы,
 *    размер мира, мёртвая зона. При правке опорного кадра множится вместе
 *    с ним; обратные длине величины (интервал на ячейку) — делятся.
 * 2. ОБЪЁМ И ЦЕНА — соразмерны площади, то есть квадрату длины: ёмкость
 *    инвентаря, пропускная способность, цены. Вдвое более широкая кисть
 *    выносит вчетверо больше вещества.
 * 3. СОРАЗМЕРНОЕ ПЕРСОНАЖУ — от кадра не зависит: хитбокс, спрайт, автоподъём.
 *    Спрайт нарисован в ячейках и с окном не растёт, поэтому мерка «доля роста»
 *    работает только здесь; всё остальное меряется кадром и рельефом.
 */

