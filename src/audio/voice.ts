/**
 * Контракт дорожки.
 *
 * Добавление звука новой механике — это новый файл в `voices/`, блок в конфиге
 * и одна строка в реестре `soundscape.ts`. Ни ядро, ни соседние дорожки,
 * ни сама механика при этом не правятся.
 *
 * Импорты здесь только типовые: файл ничего не тянет в рантайм и не мешает
 * проверять модели дорожек в Node.
 */
import type { AudioBus } from './context';
import type { VoiceSlots } from './model';
import type { AudioSignals } from './signals';

export interface Voice {
  /** Идентификатор дорожки. Совпадает с именем блока в `AUDIO`. */
  readonly id: string;
  /** Собственный выключатель: дорожку должно быть можно слушать в одиночку. */
  readonly enabled: boolean;

  /** Построить постоянный граф. Вызывается один раз, когда контекст появился. */
  build(bus: AudioBus, slots: VoiceSlots): void;

  /**
   * Шаг дорожки.
   *
   * @param at время, на которое планируется звучащее в этом шаге
   * @param now `ctx.currentTime` — нужен для учёта занятости слотов
   */
  update(dt: number, signals: AudioSignals, at: number, now: number): void;

  /**
   * Фокус вернулся: приравнять сглаженные величины к текущему сигналу.
   * Без этого дорожка догоняла бы своё состояние от значения, накопленного
   * до сворачивания вкладки.
   */
  resync(): void;
}
