/**
 * Детерминированный шум мира.
 *
 * Вынесено из генератора Луны, потому что задник строится теми же средствами
 * и из того же зерна: два независимых генератора шума разошлись бы по стилю
 * форм, и рельеф с силуэтами на горизонте перестали бы выглядеть одной планетой.
 * По той же причине здесь же лежит хеш координат: им пользуются и клеточный
 * автомат, и копание.
 */

/** Детерминированный ГПСЧ (mulberry32): одно зерно — один и тот же мир. */
export function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/**
 * Детерминированное «случайное» число в [0,1) от целых аргументов.
 *
 * Не генератор: у каждой точки своё значение, и оно не зависит ни от порядка
 * обхода, ни от того, спрашивали ли уже про соседей. Поведение мира обязано
 * быть воспроизводимым — иначе его нельзя ни проверить, ни повторить
 * по сообщению об ошибке.
 *
 * `salt` разводит независимые решения по одним и тем же координатам: автомат
 * передаёт номер шага, копание — свою постоянную.
 */
export function hashChance(x: number, y: number, salt: number): number {
  let h = Math.imul(x, 374761393) + Math.imul(y, 668265263) + Math.imul(salt, 2246822519);
  h = Math.imul(h ^ (h >>> 13), 1274126177);
  return ((h ^ (h >>> 16)) >>> 0) / 4294967296;
}

/**
 * Сглаженный одномерный шум по опорным точкам. Возвращает значение в [-1, 1].
 *
 * Период равен единице аргумента: `noise(0)` и `noise(1)` дают одно значение.
 * На этом держится бесшовная закольцовка силуэтов задника.
 */
export function makeNoise(rand: () => number, points: number): (t: number) => number {
  const values = new Float32Array(points);
  for (let i = 0; i < points; i++) values[i] = rand() * 2 - 1;
  return (t: number) => {
    const p = t * points;
    const i = Math.floor(p);
    const f = p - i;
    const i0 = ((i % points) + points) % points;
    const i1 = (i0 + 1) % points;
    const s = f * f * (3 - 2 * f); // smoothstep — без изломов на стыках
    return values[i0]! + (values[i1]! - values[i0]!) * s;
  };
}
