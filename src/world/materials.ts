/**
 * Таблица материалов.
 *
 * Ячейка мира хранит только id материала (один байт). Все свойства берутся
 * отсюда по этому id — так мир 1024x512 занимает 512 КБ вместо мегабайтов
 * объектов, и его можно передать в WASM без копирования, когда симуляция
 * туда переедет.
 *
 * Ключевое разделение: `blocksPlayer` и правила движения — РАЗНЫЕ вещи.
 * Коллизия персонажа читает первое, симуляция — `state` и `density`. Пока это
 * было одно поле, воду выразить было нельзя: сквозь неё персонаж проваливается,
 * но песок в ней тонет, а не проходит насквозь.
 */

/** Агрегатное состояние: определяет, какой набор правил применяет симуляция. */
export const MatterState = {
  Void: 0,
  /** Не двигается никогда и не вытесняется, какова бы ни была плотность. */
  Solid: 1,
  /** Вниз, затем по диагонали вниз-вбок. */
  Powder: 2,
  /** Вниз, затем по диагонали вниз-вбок, затем вбок на дальность растекаемости. */
  Liquid: 3,
  /** Зеркало жидкости: вверх, затем верхние диагонали, затем вбок. */
  Gas: 4,
} as const;

export type MatterStateValue = (typeof MatterState)[keyof typeof MatterState];

export interface Material {
  readonly id: number;
  readonly name: string;
  /** Цвет вида 0xRRGGBB. Для пустоты не используется — она показывает фон мира. */
  readonly color: number;
  /**
   * Останавливает ли персонажа. НЕ участвует в правилах движения материала —
   * вода персонажа не держит, но песок в неё тонет, а не проваливается сквозь.
   */
  readonly blocksPlayer: boolean;
  /** Кто кого вытесняет: плотное тонет в менее плотном, газ всплывает в более плотном. */
  readonly density: number;
  readonly state: MatterStateValue;
  /**
   * Жидкости: сколько ячеек вбок проходит за шаг, когда вниз и по диагонали
   * занято. Дальность одного смещения, а не вязкость.
   */
  readonly spread: number;
  /**
   * Жидкости: доля шагов, на которых материал вообще пытается двигаться, 0..1.
   * 1 — вода, ближе к нулю — расплав. Вязкость выражается ЗДЕСЬ, а не нулевой
   * растекаемостью: жидкость без бокового течения складывается в кучу под углом
   * естественного откоса и становится неотличима от песка.
   */
  readonly flow: number;
  /**
   * Сыпучие: насколько охотно скатывается по диагонали, 0..1.
   * 1 — расплывается пологой кучей, ближе к 0 — держит крутой склон.
   */
  readonly slip: number;
  /** Газы: вероятность исчезнуть за шаг. Иначе газ копится под потолком вечно. */
  readonly dissipate: number;
  /**
   * Что отдаёт разрушенная ячейка: id материала выработки.
   *
   * Выработка — свойство того, что копают, а не инструмента, которым копают.
   * Порода отдаёт рыхлый реголит, лёд — воду. Пока добываемое вещество было
   * одно, выработку можно было держать константой копания; с двумя разными
   * продуктами каждое новое вещество означало бы ветку по идентификатору
   * материала в коде копания — ровно то, чего архитектура избегает везде.
   */
  readonly yields: number;
  /**
   * Доля ячеек выемки, отдающих выработку. Остальные становятся пустотой.
   *
   * Живёт ЗДЕСЬ, а не в настройках кисти, по той же причине, что и плотность
   * с осыпаемостью: разные вещества отдают разное и в разном количестве.
   * Радиус, дальность и темп кисти остаются в конфиге — они свойства
   * инструмента; доля выработки свойством инструмента не является.
   *
   * ОБЯЗАНА быть строго между нулём и единицей, и обе границы существенны.
   * Единица — превращение ячейка в ячейку: объём не меняется, под каждой новой
   * ячейкой выработки остаётся исходное вещество, падать некуда, и копание
   * сводится к смене цвета. Ноль — потеря добычи: инструмент становится ластиком.
   */
  readonly yieldRate: number;
  /**
   * Берётся ли вещество в инвентарь пылесосом.
   *
   * Отдельно от состояния: состояние отвечает, КАК вещество движется,
   * переносимость — можно ли его унести. Статичное непереносимо по смыслу
   * (подобрать породу пылесосом — это копание со своими правилами
   * и своей выработкой), но обратное неверно: жидкости и газы тоже
   * непереносимы, а состояние у них подвижное.
   */
  readonly portable: boolean;
  /**
   * Берёт ли вещество кисть копания.
   *
   * Нужна ОТДЕЛЬНО от состояния, потому что копается всё статичное, а корпус
   * посадочного модуля обязан быть статичным (по нему ходят) и при этом
   * неразрушимым. Выразить это состоянием нельзя, а без признака единственную
   * точку сдачи в мире сносит собственный инструмент за один клик.
   *
   * По умолчанию разрушаемо: исключения перечисляются в таблице поимённо,
   * чтобы неразрушимость нельзя было получить забывчивостью.
   */
  readonly diggable: boolean;
  /**
   * Сколько кредитов приносит одна ячейка, попавшая в приёмник. Ноль —
   * вещество не принимается.
   *
   * Живёт здесь, а не в приёмнике, по той же причине, что и выработка в копании:
   * приёмник не должен знать названий веществ, а новое принимаемое вещество
   * обязано быть строкой таблицы.
   */
  readonly credits: number;
  /**
   * В какую сторону вещество тащит лежащее НА нём сыпучее: −1 влево, +1 вправо,
   * 0 — никуда. Ненулевой перенос делает вещество несущей поверхностью.
   *
   * Живёт здесь по той же причине, что и все прочие правила: автомат выбирает
   * поведение по признаку вещества, а не по его имени. Ветка `if (это конвейер)`
   * внутри `movePowder` означала бы, что вторая несущая поверхность — правка
   * симуляции, а не строка таблицы.
   *
   * Читается ИЗ ЯЧЕЙКИ ПОД грузом: правило принадлежит грузу, а не поверхности.
   * Если бы решение принимала лента, её пришлось бы обходить каждый шаг,
   * и пустая лента будила бы чанки просто фактом существования.
   */
  readonly carry: -1 | 0 | 1;
}

