/**
 * Значения по умолчанию: у большинства материалов задействована часть полей.
 *
 * Выработка по умолчанию — рыхлый реголит в доле 0.35. Это прежняя константа
 * копания `DIG.yield`, переехавшая сюда вместе с обоснованием.
 *
 * Значение выведено из числа проходов на проходимый ход, а не подобрано
 * на глаз: кисть радиуса 3 накрывает 29 ячеек, 0.35 даёт ~10 ячеек материала
 * и ~19 пустоты. За проход образуется ход высотой ~7 ячеек, из которых ~2.5
 * занимает осыпавшаяся выработка, — персонаж высотой 10 в один проход
 * не пролезает, нужно 2–3. Копание ощущается работой, а не прорезанием масла.
 *
 * Физическое обоснование самой доли: порода плотная, при дроблении часть уходит
 * в мелкую пыль, а в вакууме её ничто не удержит облаком — на Луне нет воздуха.
 * Восстанавливается только крупная фракция.
 *
 * Материалам, которые не копаются вовсе (пустота, жидкости, газ), эти поля
 * достаются как любому другому значению по умолчанию и никогда не читаются:
 * копают только статичное.
 *
 * Переносимость, ставка сдачи и перенос по умолчанию НУЛЕВЫЕ, а разрушаемость —
 * положительная. Умолчания выбраны так, чтобы забывчивость давала безопасный
 * результат: незаполненное поле означает «не уносится, не принимается и никого
 * никуда не тащит», а не «уносится и стоит денег». Неразрушимость —
 * единственное исключение из этого правила, и потому она перечисляется поимённо.
 */
