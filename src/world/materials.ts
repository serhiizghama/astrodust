/**
 * Таблица материалов. Ячейка мира хранит один байт — id; всё остальное берётся
 * отсюда, поэтому мир 1024×512 занимает 512 КБ и передаётся в WASM без копии.
 *
 * Инвариант: `blocksPlayer` и правила движения — РАЗНЫЕ вещи. Коллизия читает
 * первое, автомат — `state` и `density`. Одним полем воду не выразить: сквозь
 * неё персонаж проваливается, но песок в ней тонет, а не проходит насквозь.
 *
 * Цвета — только из `RAMP`. Природное и рукотворное различаются семейством
 * лестницы, а не оттенком внутри одного.
 */

import { RAMP } from '../palette';

/** Агрегатное состояние: определяет, какой набор правил применяет симуляция. */
export const MatterState = {
  Void: 0,
  /** Не двигается никогда и не вытесняется, какова бы ни была плотность. */
  Solid: 1,
  /** Вниз, затем по диагонали вниз-вбок. */
  Powder: 2,
  /** Вниз, затем по диагонали вниз-вбок, затем вбок на дальность растекаемости. */
  Liquid: 3,
  /** Зеркало жидкости: вверх, затем верхние диагонали, затем вбок. */
  Gas: 4,
} as const;

export type MatterStateValue = (typeof MatterState)[keyof typeof MatterState];

export interface Material {
  readonly id: number;
  readonly name: string;
  /** Цвет вида 0xRRGGBB. Для пустоты не используется — она показывает фон мира. */
  readonly color: number;
  /** Останавливает ли персонажа. Правилами движения вещества НЕ читается. */
  readonly blocksPlayer: boolean;
  /** Кто кого вытесняет: плотное тонет в менее плотном, газ всплывает в более плотном. */
  readonly density: number;
  readonly state: MatterStateValue;
  /**
   * Жидкости: сколько ячеек вбок проходит за шаг, когда вниз и по диагонали
   * занято. Дальность одного смещения, а не вязкость.
   */
  readonly spread: number;
  /**
   * Жидкости: доля шагов, на которых вещество пытается двигаться, 0..1.
   * Вязкость выражается ЗДЕСЬ, а не нулевой растекаемостью: жидкость без
   * бокового течения складывается в кучу и неотличима от песка.
   */
  readonly flow: number;
  /**
   * Сыпучие: насколько охотно скатывается по диагонали, 0..1.
   * 1 — расплывается пологой кучей, ближе к 0 — держит крутой склон.
   */
  readonly slip: number;
  /** Газы: вероятность исчезнуть за шаг. Иначе газ копится под потолком вечно. */
  readonly dissipate: number;
  /**
   * Что отдаёт разрушенная ячейка. Свойство того, что копают, а не инструмента:
   * иначе новое вещество означало бы ветку по id внутри копания.
   */
  readonly yields: number;
  /**
   * Доля ячеек выемки, отдающих выработку; остальные становятся пустотой.
   *
   * Инвариант: строго между 0 и 1, обе границы существенны. Единица — объём
   * не меняется, падать некуда, копание сводится к смене цвета. Ноль —
   * инструмент становится ластиком.
   */
  readonly yieldRate: number;
  /**
   * Берётся ли вещество в инвентарь. Отдельно от состояния: подвижность
   * не влечёт переносимости — жидкости и газы подвижны и непереносимы.
   */
  readonly portable: boolean;
  /**
   * Берёт ли вещество кисть копания. Отдельно от состояния: корпус модуля
   * статичен (по нему ходят) и обязан быть неразрушим, иначе единственную
   * точку сдачи сносит собственный инструмент за клик.
   *
   * По умолчанию разрушаемо — неразрушимость нельзя получить забывчивостью.
   */
  readonly diggable: boolean;
  /**
   * Кредитов за ячейку, попавшую в приёмник. Приёмник не знает имён веществ.
   * Ноль — вещество не принимается вовсе.
   *
   * Инвариант: ставка РАСТЁТ вдоль цепочки переработки — реголит дешевле
   * пульпы, пульпа дешевле иридия. В этом весь смысл передела, и держит его
   * `tests/landing-module.ts`.
   */
  readonly creditRate: number;
  /**
   * Куда вещество тащит лежащее НА нём сыпучее: −1, 0, +1. Ненулевое делает
   * вещество несущей поверхностью.
   *
   * Читается ИЗ ЯЧЕЙКИ ПОД грузом — правило принадлежит грузу, а не поверхности.
   * Иначе ленту пришлось бы обходить каждый шаг, и пустая лента будила бы чанки
   * фактом своего существования.
   */
  readonly carry: -1 | 0 | 1;
  /**
   * Сколько света вещество отдаёт вокруг себя, 0..15. Ноль — не светится.
   *
   * Свойство ВЕЩЕСТВА, а не отрисовки: лава светит потому, что она лава, и
   * новое светящееся вещество не должно требовать ветки в рендере. Как именно
   * свет ложится на соседей — вопрос представления и решается там.
   */
  readonly emit: number;
}

