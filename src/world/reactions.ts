import { World } from './world';
import { MAT, MATERIALS } from './materials';

/**
 * Реакции веществ: пара соприкасающихся ячеек превращается в пару продуктов.
 *
 * Реакция — слой ПОВЕРХ клеточного автомата, а не ветка внутри него. Автомат
 * знает о ней ровно одно: после успешного перемещения надо спросить, не возникло
 * ли нового соприкосновения. Всё остальное — здесь, и добавление реакции обязано
 * быть строкой таблицы ниже.
 *
 * Соприкосновение — соседство ПО СТОРОНЕ. Диагональ в пиксельной модели
 * контактом не является: две ячейки, разделённые углом двух стенок, физически
 * не касаются, и реакция через такой угол выглядела бы просачиванием.
 *
 * Сохранение вещества: пара на входе даёт пару на выходе. Инвариант «вещество
 * не исчезает» держится во всей остальной модели, и реакция не имеет права
 * его нарушать — иначе непроверяемым становится любое утверждение о сохранении,
 * включая уже описанные для вытеснения и подъёма.
 */
export interface Reaction {
  readonly a: number;
  readonly b: number;
  readonly toA: number;
  readonly toB: number;
}

export const REACTIONS: readonly Reaction[] = [
  /**
   * Рыхлый реголит + вода = две ячейки пульпы.
   *
   * Первая и пока единственная реакция. Она — то, ради чего вода вообще
   * ресурс: без неё лёд остаётся декорацией, а весь экономический цикл
   * сводится к сдаче сырья.
   */
  { a: MAT.REGOLITH_LOOSE, b: MAT.WATER, toA: MAT.PULP, toB: MAT.PULP },
];

const size = MATERIALS.length;

/**
 * Таблица переходов, развёрнутая по паре идентификаторов.
 *
 * Плоские массивы, а не поиск по списку: проверка выполняется на каждое
 * успешное перемещение ячейки, то есть в самом горячем месте автомата.
 * Пара записывается в обе стороны — порядок соседей заранее неизвестен.
 *
 * Ноль значит «реакции нет»: нулевой идентификатор — пустота, и продуктом
 * она быть не может по построению (реакция сохраняет количество ячеек,
 * а пустота его уменьшила бы).
 */
const PRODUCT_A = new Uint8Array(size * size);
const PRODUCT_B = new Uint8Array(size * size);

/**
 * Участвует ли вещество хоть в одной реакции.
 *
 * Ранний отказ по одному обращению к массиву. Подавляющее большинство
 * перемещений в мире делают вещества, которые ни с чем не реагируют, и платить
 * за них обходом четырёх соседей нельзя.
 */
export const MAT_REACTIVE = new Uint8Array(size);

for (const r of REACTIONS) {
  PRODUCT_A[r.a * size + r.b] = r.toA;
  PRODUCT_B[r.a * size + r.b] = r.toB;
  PRODUCT_A[r.b * size + r.a] = r.toB;
  PRODUCT_B[r.b * size + r.a] = r.toA;
  MAT_REACTIVE[r.a] = 1;
  MAT_REACTIVE[r.b] = 1;
}

/**
 * Проверяет четыре соседа ячейки по стороне и применяет первую подошедшую
 * реакцию.
 *
 * Порядок обхода фиксирован (вверх, вниз, влево, вправо), поэтому результат
 * детерминирован: одинаковое состояние сетки даёт одинаковый исход независимо
 * от того, сколько соседей подошло. Больше одной реакции за вызов не бывает —
 * ячейка, ставшая продуктом, в исходном виде больше не существует.
 *
 * Ячейки продуктов пишутся через `world.set`, а не напрямую: продукт обязан
 * подчиняться своим правилам движения с первого же шага, а для этого его
 * окрестность должна проснуться, как от любой другой записи. Ничего сверх этих
 * двух пробуждений реакция не делает — а не сработав, не делает ни одного.
 *
 * @returns сработала ли реакция
 */
export function reactAround(world: World, x: number, y: number): boolean {
  const m = world.get(x, y);
  if (MAT_REACTIVE[m] !== 1) return false;

  const row = m * size;
  // Соседи перечислены явно, а не циклом по массиву смещений: обход четырёх
  // фиксированных направлений не стоит аллокации на каждое перемещение ячейки.
  if (tryPair(world, row, x, y, x, y - 1)) return true;
  if (tryPair(world, row, x, y, x, y + 1)) return true;
  if (tryPair(world, row, x, y, x - 1, y)) return true;
  return tryPair(world, row, x, y, x + 1, y);
}

function tryPair(world: World, row: number, x: number, y: number, nx: number, ny: number): boolean {
  // За пределами сетки `world.get` отдаёт породу — она ни с чем не реагирует,
  // поэтому отдельной проверки границ здесь не нужно.
  const n = world.get(nx, ny);
  const a = PRODUCT_A[row + n]!;
  if (a === 0) return false;

  world.set(x, y, a);
  world.set(nx, ny, PRODUCT_B[row + n]!);
  return true;
}
