import { DIG } from '../config';
import {
  World,
  MAT,
  MAT_STATE,
  MAT_YIELDS,
  MAT_YIELD_RATE,
  MAT_DIGGABLE,
  MatterState,
  hashChance,
} from '../world';

/**
 * Копание: выемка твёрдого вещества, часть которой возвращается выработкой.
 *
 * Что именно возвращается и в какой доле — свойство РАЗРУШЕННОГО материала,
 * а не копания: порода отдаёт рыхлый реголит, лёд отдаёт воду. Здесь нет и
 * не должно появиться ни одной ветки по идентификатору вещества — оба ответа
 * читаются из таблицы материалов. Добавление добываемого вещества обязано быть
 * строкой таблицы, а не правкой этого файла.
 *
 * Выработка МЕНЬШЕ выемки, и это не условность, а условие работы физики.
 * При превращении ячейка в ячейку объём не меняется: под каждой новой ячейкой
 * выработки остаётся исходное вещество, правило «падать, если снизу свободно»
 * не срабатывает никогда, и копание сводится к смене цвета. Замер на сплошной
 * породе показал это точно: 29 превращённых ячеек, 0 образованной пустоты,
 * 0 движения за 300 шагов. Для воды ограничение то же: без свободного объёма
 * ей некуда течь.
 *
 * Обратная крайность не лучше: удаление всего превратило бы мышь в ластик —
 * добывать нечего, физика сыпучего не задействована. Рабочее правило не
 * «превращать всё» и не «удалять всё», а «обязательно что-то отдавать».
 *
 * Смещение хеша для выбора отдающих ячеек: автомат пользуется тем же хешем
 * и на нулевом шаге дал бы ровно те же числа — рисунок выработки совпал бы
 * с рисунком скатывания. Ничего бы не сломалось, но два независимых правила
 * оказались бы связаны там, где связи нет.
 */
const YIELD_SALT = 0x5eed1;

export class Digger {
  private cooldown = 0;

  /** Достижима ли точка мира с текущей позиции персонажа. */
  static inReach(playerCX: number, playerCY: number, targetX: number, targetY: number): boolean {
    const dx = targetX - playerCX;
    const dy = targetY - playerCY;
    return dx * dx + dy * dy <= DIG.reach * DIG.reach;
  }

  /**
   * @returns размер выемки этого шага (см. `applyBrush`)
   */
  update(
    dt: number,
    world: World,
    held: boolean,
    playerCX: number,
    playerCY: number,
    targetX: number,
    targetY: number,
  ): number {
    this.cooldown = Math.max(0, this.cooldown - dt);
    if (!held) return 0;
    // Темп задаётся интервалом, а не частотой кадров: иначе на 144 Гц
    // копалось бы вдвое быстрее, чем на 60.
    if (this.cooldown > 0) return 0;

    // Недостижимая цель не меняет мир ВООБЩЕ — ни частично, ни по ближайшей
    // достижимой точке. Игрок целится в одно, копалось бы другое.
    if (!Digger.inReach(playerCX, playerCY, targetX, targetY)) return 0;

    this.cooldown = DIG.interval;
    return Digger.applyBrush(world, targetX, targetY);
  }

  /**
   * Круглая кисть: все статичные РАЗРУШАЕМЫЕ ячейки в радиусе разрушаются,
   * доля `yieldRate` разрушенного материала становится его выработкой,
   * остальные — пустотой.
   *
   * Разрушается СТАТИЧНОЕ, а не «то, что блокирует персонажа»: прежнее условие
   * пользовалось полем коллизии как признаком разрушаемости и вынуждено было
   * отдельно вычитать из него рыхлый реголит — тот тоже держит персонажа.
   * Множество веществ у обоих правил совпадает ячейка в ячейку, но по состоянию
   * оно формулируется одной проверкой и не опирается на совпадение, которое
   * не обязано сохраняться. Следствие: жидкости и газы не копаются
   * по построению, а не потому, что их флаг коллизии удачно совпал.
   *
   * Пустые ячейки не трогаются — копать нечего, выработка из воздуха не
   * появляется. Уже рыхлый материал тоже: его уборка относится к сбору
   * в инвентарь, а не к копанию.
   *
   * Кисть, накрывшая ячейки разных материалов, отдаёт выработку каждого из них
   * по его собственному правилу — за одно применение, без разделения на проходы.
   *
   * @returns размер ВЫЕМКИ — сколько ячеек разрушено. Выработка меньше,
   *   и наружу она не нужна: единственный читатель — звук, а помол звучит
   *   по объёму перемолотой породы, а не по тому, сколько из неё уцелело.
   */
  static applyBrush(world: World, centerX: number, centerY: number): number {
    const r = DIG.radius;
    const rSq = r * r;
    let excavated = 0;
    let yielded = 0;
    // Первая разрушенная ячейка в порядке обхода — запасная выработка.
    // Материал запоминается вместе с координатами: запасное правило обязано
    // отдать выработку ИМЕННО ЭТОГО вещества, иначе кисть по краю ледяной линзы
    // вернула бы игроку реголит — вещество, которого во льду нет.
    let firstX = 0;
    let firstY = 0;
    let firstMaterial: number = MAT.VACUUM;

    for (let dy = -r; dy <= r; dy++) {
      for (let dx = -r; dx <= r; dx++) {
        if (dx * dx + dy * dy > rSq) continue; // круг, а не квадрат
        const x = centerX + dx;
        const y = centerY + dy;
        if (x < 0 || y < 0 || x >= world.width || y >= world.height) continue;

        const m = world.get(x, y);
        if (MAT_STATE[m] !== MatterState.Solid) continue;
        // Неразрушимое не меняется и НЕ СЧИТАЕТСЯ выемкой. Второе так же важно,
        // как первое: попади корпус модуля в счёт, кисть по нему звучала бы
        // помолом и могла бы сработать запасным правилом ненулевой выработки —
        // то есть отдать реголит за то, что не разрушено.
        if (MAT_DIGGABLE[m] !== 1) continue;

        if (excavated === 0) {
          firstX = x;
          firstY = y;
          firstMaterial = m;
        }
        excavated++;

        // Отдающие ячейки рассеяны по всей выемке, а не собраны сверху.
        // При рассеянии часть материала оказывается на своде полости и падает,
        // часть уже лежит на дне и остаётся — получается осыпь. Складывание
        // всей выработки наверх давало бы одинаковый эффектный обвал на каждый
        // клик, и это быстро прочиталось бы как анимация, а не как физика.
        if (hashChance(x, y, YIELD_SALT) < MAT_YIELD_RATE[m]!) {
          world.set(x, y, MAT_YIELDS[m]!);
          yielded++;
        } else {
          world.set(x, y, MAT.VACUUM);
        }
      }
    }

    // Кисть, не отдавшая ничего, читается как поломка: игрок бьёт по камню
    // и остаётся ни с чем. На малой площади касания — край породы, узкая
    // перемычка — хеш легко даёт ноль на всех ячейках сразу. Порядок обхода
    // фиксирован, поэтому запасное правило остаётся детерминированным.
    if (excavated > 0 && yielded === 0) world.set(firstX, firstY, MAT_YIELDS[firstMaterial]!);

    return excavated;
  }
}
