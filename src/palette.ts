/**
 * Палитра проекта: 46 цветов, разбитых на семь тональных лестниц.
 *
 * ЕДИНСТВЕННОЕ место в проекте, где разрешён шестнадцатеричный литерал цвета.
 * Правило существует ради дифа: пока цвета лежат по месту использования, выход
 * за гамму выглядит как обычная правка константы и проходит ревью незамеченным.
 * Здесь та же правка выглядит изменением самой палитры — то есть заметна.
 * Автоматической проверки «цвет из набора» нет и не будет: разбор исходников
 * регулярным выражением ловит не только цвета (полином CRC, соль генератора,
 * маска канала), а сканирование готового кадра покрывает лишь те поверхности,
 * которые в этот кадр попали. Источник правды решает задачу надёжнее теста.
 *
 * Внутри каждой лестницы цвета идут ОТ ТЁМНОГО К СВЕТЛОМУ, и порядок — часть
 * контракта, а не оформление. Индекс выражает ОТНОШЕНИЕ между поверхностями,
 * а не имя оттенка: `RAMP.earth[2]` читается как «третья ступень земляной
 * лестницы», соседняя поверхность берёт `RAMP.earth[4]`, и «на две ступени
 * светлее» видно прямо в коде, без обращения к таблице цветов. Именованная
 * константа (`ROCK_BROWN`) фиксировала бы назначение и при перекраске начинала
 * бы врать; индекс назначения не имеет и перекраску переживает.
 *
 * Две соседние ступени одной лестницы НЕ назначаются двум поверхностям, которые
 * игрок обязан различать: одна ступень читается как оттенок освещения, а не как
 * другое вещество. Различимость задаётся расстоянием по лестнице, а где запаса
 * по яркости нет — разницей тона: она берётся глазом всегда.
 *
 * В МИРОВОМ кадре промежуточных оттенков не бывает. Смешивание, затемнение и
 * интерполяция на лету — это выход за набор; плавный переход задаётся
 * дизерингом, а не третьим цветом.
 *
 * В слое интерфейса разрешена ПРОЗРАЧНОСТЬ: подложки, тени и сглаженные края
 * букв смешиваются с тем, что под ними. Базовый цвет при этом остаётся цветом
 * набора, и берётся он через `css()` — записанная руками строка `rgba(...)`
 * теряет связь с лестницей, и перекраска палитры её не достаёт.
 */
export const RAMP = {
  blue: [0x172038, 0x253a5e, 0x3c5e8b, 0x4f8fba, 0x73bed3, 0xa4dddb],
  green: [0x19332d, 0x25562e, 0x468232, 0x75a743, 0xa8ca58, 0xd0da91],
  earth: [0x4d2b32, 0x7a4841, 0xad7757, 0xc09473, 0xd7b594, 0xe7d5b3],
  warm: [0x341c27, 0x602c2c, 0x884b2b, 0xbe772b, 0xde9e41, 0xe8c170],
  rust: [0x241527, 0x411d31, 0x752438, 0xa53030, 0xcf573c, 0xda863e],
  violet: [0x1e1d39, 0x402751, 0x7a367b, 0xa23e8c, 0xc65197, 0xdf84a5],
  gray: [
    0x090a14, 0x10141f, 0x151d28, 0x202e37, 0x394a50, 0x577277, 0x819796, 0xa8b5b2, 0xc7cfcc,
    0xebede9,
  ],
} as const;

/**
 * Цвет набора для канваса, при необходимости с прозрачностью.
 *
 * Единственный способ получить цвет интерфейса: непрозрачная составляющая
 * приходит из `RAMP`, и связь с лестницей сохраняется в коде видимой.
 */
export function css(color: number, alpha = 1): string {
  const r = (color >> 16) & 0xff;
  const g = (color >> 8) & 0xff;
  const b = color & 0xff;
  return `rgba(${r},${g},${b},${alpha})`;
}
