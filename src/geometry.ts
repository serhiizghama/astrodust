/**
 * Прямоугольник в ячейках мира.
 *
 * Один тип на всё, что описывается четвёркой «угол плюс размер»: приёмная зона
 * модуля, область, занятая персонажем, границы постройки. Два независимых
 * объявления одной и той же четвёрки разошлись бы на первой правке, а
 * преобразовывать одно в другое было бы нечем — это одна и та же вещь.
 */
export interface Rect {
  readonly x: number;
  readonly y: number;
  readonly w: number;
  readonly h: number;
}
