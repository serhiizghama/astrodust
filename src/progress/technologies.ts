import type { TuningParam } from './tuning';

/**
 * Дерево технологий — ТАБЛИЦА ЗАПИСЕЙ, а не набор веток кода.
 *
 * ```
 *   технология               цена, ₡  требует             эффект
 *   Вакуумный пылесос           600      —                 открыть: режим сбора
 *   Конвейерная лента           600      —                 открыть: конвейеры
 *   Широкий раструб             960    Вакуумный пылесос   параметр: радиус сбора 8
 *   Раструб повышенной тяги    2400    Широкий раструб     параметр: радиус сбора 10
 *   Форсированные сопла        3000      —                 параметр: предел подъёма 280
 * ```
 *
 * Добавление технологии обязано быть строкой этой таблицы. Как только эффект
 * становится функцией, дерево перестаёт расти без правок движка — а расти
 * строками оно должно именно потому, что его будут растить.
 */

/**
 * Что технология открывает. Идентификатор СОДЕРЖИМОГО, а не вида постройки:
 * одна технология открывает оба направления ленты, и ссылаться ей надо
 * на то, чем они являются вместе, а не на два вида по отдельности.
 *
 * Содержимым бывает и постройка, и режим инструмента: вид эффекта у них один,
 * и заводить второй ради того, что открывается слот панели, а не строка
 * каталога, значило бы менять движок на каждый новый род награды.
 */
export const CONTENT = {
  /** Оба направления конвейера сразу. */
  CONVEYOR: 'conveyor',
  /** Режим сбора: сам пылесос, его инвентарь и высыпание из него. */
  VACUUM: 'vacuum',
} as const;

/**
 * Эффект — данные ровно двух видов.
 *
 * Третьего вида нет намеренно: он заводится тогда, когда появляется третья
 * потребность, а не заранее. Двух хватает на всё, что заявлено, — открыть
 * содержимое и задать параметр.
 */
export type TechEffect =
  | { readonly kind: 'unlock'; readonly content: string }
  | { readonly kind: 'tune'; readonly param: TuningParam; readonly value: number };

export interface Technology {
  readonly id: string;
  readonly name: string;
  /** Пояснение для оверлея: что технология даёт словами, а не полем эффекта. */
  readonly description: string;
  /**
   * Как этим пользоваться: какой режим, какая клавиша, что именно меняется.
   *
   * Отдельно от `description`: пояснение отвечает «что это», применение —
   * «что с этим делать». Второй вопрос возникает ровно у того, кто технологию
   * ещё не купил, и ответ на него решает, покупать ли.
   */
  readonly usage: string;
  /**
   * КЛЮЧ значка, а не картинка: таблица про пиксели ничего не знать не обязана,
   * а рендер по ключу берёт спрайт. Неизвестный ключ получает запасной значок —
   * новая технология обязана оставаться строкой таблицы и без своей картинки.
   */
  readonly icon: string;
  /** Цена в кредитах — той же валюте, что растёт на сдаче вещества. */
  readonly cost: number;
  /**
   * Технологии, без которых эта недоступна.
   *
   * СПИСОК, а не одна ссылка: «требует A и B» появится на первом же узле,
   * объединяющем две ветки, и список из нуля-двух элементов стоит ровно
   * столько же, сколько одна ссылка, тогда как переделка стоит дороже.
   */
  readonly requires: readonly string[];
  readonly effect: TechEffect;
}

