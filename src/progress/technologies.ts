/** Поиск по идентификатору: покупка спрашивает по имени, а не по индексу. */
export const TECH_BY_ID: ReadonlyMap<string, Technology> = new Map(
  TECHNOLOGIES.map((t) => [t.id, t]),
);

/**
 * Предел параметра по всему дереву — максимум по столбцу. Нужен проверкам:
 * игра, корректная только до первой покупки, корректной не является. Считается
 * по таблице — выписанное рядом число разошлось бы с ней на первой технологии.
 */
export function maxTuned(param: TuningParam, base: number): number {
  let best = base;
  for (const t of TECHNOLOGIES) {
    if (t.effect.kind === 'tune' && t.effect.param === param && t.effect.value > best) {
      best = t.effect.value;
    }
  }
  return best;
}
