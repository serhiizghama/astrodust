import type { TuningParam } from './tuning';

/**
 * Дерево технологий — ТАБЛИЦА ЗАПИСЕЙ, а не набор веток кода.
 *
 * ```
 *   технология              стоимость  требует           эффект
 *   Конвейерная лента           5        —               открыть: конвейеры
 *   Широкий раструб             8        —               параметр: радиус сбора 4
 *   Раструб повышенной тяги    20      Широкий раструб   параметр: радиус сбора 5
 *   Форсированные сопла        25        —               параметр: предел подъёма 140
 * ```
 *
 * Добавление технологии обязано быть строкой этой таблицы. Как только эффект
 * становится функцией, дерево перестаёт расти без правок движка — а расти
 * строками оно должно именно потому, что его будут растить.
 */

/**
 * Что технология открывает. Идентификатор СОДЕРЖИМОГО, а не вида постройки:
 * одна технология открывает оба направления ленты, и ссылаться ей надо
 * на то, чем они являются вместе, а не на два вида по отдельности.
 */
export const CONTENT = {
  /** Оба направления конвейера сразу. */
  CONVEYOR: 'conveyor',
} as const;

/**
 * Эффект — данные ровно двух видов.
 *
 * Третьего вида нет намеренно: он заводится тогда, когда появляется третья
 * потребность, а не заранее. Двух хватает на всё, что заявлено, — открыть
 * содержимое и задать параметр.
 */
export type TechEffect =
  | { readonly kind: 'unlock'; readonly content: string }
  | { readonly kind: 'tune'; readonly param: TuningParam; readonly value: number };

export interface Technology {
  readonly id: string;
  readonly name: string;
  /** Пояснение для оверлея: что технология даёт словами, а не полем эффекта. */
  readonly description: string;
  /** Стоимость в очках исследований. */
  readonly cost: number;
  /**
   * Технологии, без которых эта недоступна.
   *
   * СПИСОК, а не одна ссылка: «требует A и B» появится на первом же узле,
   * объединяющем две ветки, и список из нуля-двух элементов стоит ровно
   * столько же, сколько одна ссылка, тогда как переделка стоит дороже.
   */
  readonly requires: readonly string[];
  readonly effect: TechEffect;
}

/**
 * Стартовый набор: четыре технологии, три наблюдаемых вида узла.
 *
 * Числа выведены расчётом, а не подобраны. Порция сепаратора — пять ячеек
 * пульпы, из них одна становится иридием, и ставка иридия единица: одна порция
 * даёт одно очко. Отсюда стоимости читаются как «сколько порций»:
 *
 * ```
 *    5 порций → конвейерная лента       первая цель, видна сразу после машины
 *    8 порций → широкий раструб         следующая ступень, всё ещё близко
 *   20 порций → раструб повышенной тяги за ним, и только через первый
 *   25 порций → форсированные сопла     конец стартового дерева
 * ```
 *
 * Пять на первую — не осторожность, а согласование с ценой машины: сепаратор
 * за 250 ₡ не возвращает ни одного кредита, и разрыв между «потратил» и «что-то
 * открылось» обязан быть коротким, иначе покупка машины читается как ошибка,
 * а не как ступень.
 */
export const TECHNOLOGIES: readonly Technology[] = [
  {
    id: 'conveyor-belt',
    name: 'Конвейерная лента',
    description: 'Открывает конвейер в каталоге построек',
    cost: 5,
    requires: [],
    // Первая вещь, которую игрок хочет, увидев ходку «сепаратор — модуль»,
    // и потому лучшая первая цель. Оба направления одной технологией: лента,
    // которую можно вести только вправо, не решает задачу, ради которой
    // её открывают.
    effect: { kind: 'unlock', content: CONTENT.CONVEYOR },
  },
  {
    id: 'wide-nozzle',
    name: 'Широкий раструб',
    description: 'Радиус кисти сбора 4',
    cost: 8,
    requires: [],
    effect: { kind: 'tune', param: 'collectRadius', value: 4 },
  },
  {
    id: 'heavy-nozzle',
    name: 'Раструб повышенной тяги',
    description: 'Радиус кисти сбора 5',
    cost: 20,
    requires: ['wide-nozzle'],
    // Предельное значение радиуса сбора по всему дереву. Пять много меньше
    // полуширины кадра (160): пылесос остаётся инструментом, а не выгребает
    // полкадра за нажатие.
    effect: { kind: 'tune', param: 'collectRadius', value: 5 },
  },
  {
    id: 'boosted-thrusters',
    name: 'Форсированные сопла',
    description: 'Предел скорости подъёма 140',
    cost: 25,
    requires: [],
    // Растёт ПРЕДЕЛ, а не ускорение: ускорение задано множителем к гравитации
    // мира, и повышать его значило бы ломать переносимость ранца между мирами —
    // именно то свойство, ради которого множитель и введён.
    //
    // 140 строго ниже импульса прыжка (150) и заметно ниже предела падения
    // (220). Оба неравенства — инварианты ранца, и держатся они на предельном
    // значении дерева, а не на базовом.
    effect: { kind: 'tune', param: 'maxRiseSpeed', value: 140 },
  },
];

/** Поиск по идентификатору: покупка спрашивает по имени, а не по индексу. */
export const TECH_BY_ID: ReadonlyMap<string, Technology> = new Map(
  TECHNOLOGIES.map((t) => [t.id, t]),
);

/**
 * Предельное значение параметра по всему дереву — максимум по столбцу таблицы.
 *
 * Нужно проверкам инвариантов: игра, корректная только до первой покупки,
 * корректной не является, и отказ здесь проявляется у игрока, который дальше
 * всех продвинулся. Считается по таблице, а не выписывается рядом с ней:
 * выписанное число разошлось бы с таблицей на первой же новой технологии.
 */
export function maxTuned(param: TuningParam, base: number): number {
  let best = base;
  for (const t of TECHNOLOGIES) {
    if (t.effect.kind === 'tune' && t.effect.param === param && t.effect.value > best) {
      best = t.effect.value;
    }
  }
  return best;
}
