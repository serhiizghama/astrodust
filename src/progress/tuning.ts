import { PLAYER, VACUUM } from '../config';

/**
 * Профиль настраиваемых параметров: одно место, откуда читается всё, что
 * технология имеет право поменять.
 *
 * ```
 *   config.ts  ──базовые значения──▶  Tuning  ◀──пишет── технология
 *                                        │
 *                                        └──читают── сбор, ранец
 * ```
 *
 * *Почему не править константы конфига:* они `as const` и импортируются
 * напрямую в десятке мест. Мутировать импортированный объект — это глобальная
 * переменная без имени: проверка не сможет вернуть исходное значение,
 * а порядок импортов начнёт влиять на поведение.
 *
 * *Почему профиль, а не геттеры у состояния исследований:* потребитель
 * параметра не должен знать, что исследования вообще существуют. Кисть сбора
 * читает свой радиус; откуда он взялся — не её дело. Это то же разделение,
 * по которому приёмник не знает названий веществ.
 *
 * *Почему экземпляр, а не модульный синглтон:* синглтон — та же безымянная
 * глобальная переменная, только в другом файле. Экземпляр создаётся один раз
 * при запуске партии и передаётся тем, кто читает параметры; проверке достаточно
 * завести свой и не трогать чужой.
 */

/**
 * Базовые значения. Берутся из `config.ts` и НИГДЕ не переписываются заново:
 * профиль, разошедшийся с конфигом хоть на единицу, тихо превращает весь
 * существующий набор проверок в проверки другой игры.
 */
export const TUNING_BASE = {
  /** Радиус кисти сбора в ячейках. */
  collectRadius: VACUUM.radius,
  /** Предел скорости подъёма на ранце, ячеек в секунду. */
  maxRiseSpeed: PLAYER.maxRiseSpeed,
} as const;

/** Имя настраиваемого параметра. Технология правит параметр по этому имени. */
export type TuningParam = keyof typeof TUNING_BASE;

export class Tuning {
  // Тип объявлен явно, а не выведен из `TUNING_BASE`: базовые значения
  // константны, и без объявления поле получило бы литеральный тип, в котором
  // «радиус стал четырьмя» не выражается вовсе.
  collectRadius: number = TUNING_BASE.collectRadius;
  maxRiseSpeed: number = TUNING_BASE.maxRiseSpeed;

  /**
   * Задать значение параметра.
   *
   * ЗАДАТЬ, а не прибавить: прибавка зависела бы от порядка покупок и от того,
   * что уже куплено, и итоговое значение перестало бы читаться из таблицы
   * технологий. Абсолютное значение видно глазом, а предельное — это просто
   * максимум по столбцу, что и требуется для проверки инвариантов.
   */
  set(param: TuningParam, value: number): void {
    // Приведение к записи «имя → число» нужно ровно потому, что все параметры
    // профиля числовые: без него присваивание по вычисленному ключу союза
    // выводится в `never`. Условие «все параметры числовые» держится типом
    // `TUNING_BASE`, из которого выведен и сам `TuningParam`.
    (this as Record<TuningParam, number>)[param] = value;
  }

  get(param: TuningParam): number {
    return this[param];
  }

  /** Совпадает ли профиль с базовым — до единой купленной технологии обязан. */
  get isBase(): boolean {
    return (
      this.collectRadius === TUNING_BASE.collectRadius &&
      this.maxRiseSpeed === TUNING_BASE.maxRiseSpeed
    );
  }
}
