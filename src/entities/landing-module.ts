import { World } from '../world/world';
import { MAT, MAT_CREDITS } from '../world/materials';

/** Прямоугольник в координатах сетки. */
export interface Rect {
  readonly x: number;
  readonly y: number;
  readonly w: number;
  readonly h: number;
}

/**
 * Посадочный модуль: единственное место в мире, где вещество превращается
 * в кредиты.
 *
 * Корпус модуля живёт в СЕТКЕ и сюда не входит — его выкладывает генератор
 * мира. Сетка остаётся единственным источником правды о геометрии: модуль,
 * существующий только в отрисовке, персонаж прошёл бы насквозь, а вещество
 * провалилось бы сквозь его корпус. Здесь — только зона приёмника и счёт.
 *
 * Зона поглощает ЛЮБОЕ попадание, а не только высыпанное из инвентаря. Правило
 * «исчезает при высыпании» перестало бы работать в тот момент, когда вещество
 * начнёт приходить не из рук игрока: самотёком по склону уже сейчас, конвейером
 * в дальнейшем.
 */
export class LandingModule {
  /**
   * Счёт. Целый и НЕОТРИЦАТЕЛЬНЫЙ.
   *
   * Монотонно неубывающим он был ровно до появления первой траты: постройка
   * списывает средства, и «счёт не уменьшается» сменилось на «счёт не уходит
   * в минус». Долгов в модели нет и вводить их незачем — единственная трата
   * неделима, и действие, на которое не хватает, отвергается целиком.
   */
  credits = 0;

  constructor(readonly receiver: Rect) {}

  /**
   * Обход зоны приёмника — раз в шаг, по списку её ячеек.
   *
   * Проходом по прямоугольнику, а не подпиской на изменения мира: приёмник
   * маленький и неподвижный, и обойти его целиком дешевле любого механизма
   * оповещения.
   *
   * Что принимается и почём, решает таблица материалов. Названий веществ
   * приёмник не знает: ставка ноль означает «не принимается», и такое вещество
   * остаётся в мире и ведёт себя как обычно — зона приёмник, а не
   * мусоросжигатель.
   *
   * @returns сколько кредитов начислено на этом шаге
   */
  update(world: World): number {
    const { x, y, w, h } = this.receiver;
    let earned = 0;

    for (let cy = y; cy < y + h; cy++) {
      for (let cx = x; cx < x + w; cx++) {
        const rate = MAT_CREDITS[world.get(cx, cy)]!;
        if (rate === 0) continue;
        world.set(cx, cy, MAT.VACUUM);
        earned += rate;
      }
    }

    this.credits += earned;
    return earned;
  }

  /**
   * Списывает стоимость покупки.
   *
   * Всё или ничего: частичной оплаты в модели нет, и при нехватке средств счёт
   * не меняется вовсе. Возвращаемое значение — не вежливость, а единственный
   * способ для покупателя узнать, состоялась ли трата, не заглядывая в счёт
   * до и после.
   *
   * @returns удалось ли списать
   */
  spend(amount: number): boolean {
    if (amount < 0 || this.credits < amount) return false;
    this.credits -= amount;
    return true;
  }

  /** Возврат при сносе. */
  refund(amount: number): void {
    if (amount > 0) this.credits += amount;
  }
}
