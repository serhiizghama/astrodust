import { World } from '../world/world';
import { MAT } from '../world/materials';

/**
 * Здание — это ДВЕ вещи сразу, и ни одной из них по отдельности не хватает.
 *
 * Корпус живёт в СЕТКЕ: она единственный источник правды о геометрии, и сквозь
 * здание-спрайт вещество провалилось бы, не удержавшись ни на одной ячейке.
 * Персонажа корпус постройки при этом НЕ держит — он проходит насквозь, как
 * сквозь воду: «блокирует персонажа» и правила движения вещества независимы.
 *
 * Состояние живёт в РЕЕСТРЕ: у машины есть накопитель и ход обработки, а в байте
 * материала их хранить негде. Связь между сеткой и реестром — прямоугольник
 * координат в записи.
 */

/** Что показывать про машину в кадре. */
export type MachineState = 'idle' | 'working' | 'blocked';

/**
 * Описание вида постройки: всё, что известно о нём ДО постановки.
 *
 * Видов ДВА, и различает их одно поле — `create`:
 *
 * ```
 *   машина                            секционная постройка
 *   ▓▓▓▓▓▓▓▓▓▓▓▓  + запись            ▶▶▶▶  и всё
 *   ▓░░░░░░░░░░▓    { накоплено,      ▶▶▶▶
 *   ▓▓▓▓░░░░▓▓▓▓      таймер }        ▶▶▶▶
 *                                     ▶▶▶▶
 * ```
 *
 * Форма корпуса — маска, а не процедура: контур будущей постройки, выкладывание
 * при постановке и очистка при сносе обязаны говорить об одних и тех же ячейках,
 * и три независимых описания одной формы разошлись бы на первой же правке.
 */
export interface BuildingKind {
  readonly id: string;
  readonly name: string;
  readonly width: number;
  readonly height: number;
  /**
   * Цена ОДНОЙ постановки: у машины — корпус целиком, у секционной постройки —
   * одна секция.
   *
   * За постановку, а не «за метр»: игрок платит за то, что уже стоит в мире.
   * Аванс за длину, которую он ещё не проложил, требовал бы возврата за
   * непроложенное, а это второй способ считать деньги.
   */
  readonly cost: number;
  readonly hull: number;
  /** Маска корпуса построчно: 1 — корпус, 0 — пустота внутри области. */
  readonly shape: Uint8Array;
  /**
   * Шаг сетки, по которой выравнивается постройка. Ноль — центрируется на цели.
   *
   * Ненулевой шаг — не удобство, а то, чем оплачено отсутствие записи
   * в реестре: границы секции негде хранить, значит они обязаны выводиться
   * из координат. Заодно только выравнивание и делает соседние секции
   * стыкующимися — разъехавшись на ячейку по вертикали, они перестали бы
   * передавать груз.
   */
  readonly grid: number;
  /**
   * Требуется ли твёрдая ячейка под областью.
   *
   * Поле ВИДА, а не общая проверка. Машине опора обязательна: висящее
   * в воздухе здание читается как ошибка рендера. Ленте она запрещена как
   * условие — перенос вещества над пустотой и есть то, ради чего её ставят,
   * и общее правило запрещало бы ей ровно тот случай, который ей поручен.
   */
  readonly needsSupport: boolean;
  /**
   * Идентификатор СОДЕРЖИМОГО, открывающего этот вид, или `null` — открыт
   * с начала партии.
   *
   * Не флаг «закрыт», а ссылка на то, чем он открывается: два направления
   * ленты указывают на одно и то же содержимое, и требование «оба направления
   * открываются одной технологией» держится тогда по построению, а не
   * по внимательности того, кто правит таблицу.
   *
   * Хотя бы один вид обязан быть открыт с начала: каталог, пустой до первой
   * покупки, оставляет режим строительства без единого действия и читается
   * как поломка.
   */
  readonly unlock: string | null;
  /**
   * Создаёт запись реестра. `null` — секционная постройка.
   *
   * Реестр существует ради состояния, которого нет в байте материала, —
   * накопителя и хода обработки. У постройки без состояния записывать нечего,
   * а лента в экран длиной дала бы восемьдесят записей, и общий шаг обновления
   * зданий превратился бы в проход по всему, что игрок построил.
   */
  readonly create: ((x: number, y: number) => Building) | null;
}

/**
 * Секционная постройка: квадрат `size`×`size`, выровненный по своей сетке,
 * без опоры и без записи в реестре.
 *
 * Фабрика, а не выписанные поля: у всех таких построек различаются ровно
 * подпись, материал и цена, и повторять вокруг них одну и ту же обвязку
 * значило бы однажды разойтись в ней.
 *
 * Корпус сплошной: маска заполнена целиком. Пустот внутри секции быть не может
 * — иначе груз проваливался бы в неё и застревал там навсегда, потому что
 * выбраться из колодца в статичном веществе сыпучему нечем.
 */
export function sectionKind(
  id: string,
  name: string,
  hull: number,
  cost: number,
  size: number,
  unlock: string | null = null,
): BuildingKind {
  return {
    id,
    name,
    width: size,
    height: size,
    cost,
    hull,
    shape: new Uint8Array(size * size).fill(1),
    grid: size,
    needsSupport: false,
    unlock,
    create: null,
  };
}

/** Экземпляр, стоящий в мире. */
export abstract class Building {
  constructor(
    readonly kind: BuildingKind,
    readonly x: number,
    readonly y: number,
  ) {}

  /** Шаг машины. Мир меняет сама — и только тогда, когда ей есть что менять. */
  abstract update(world: World, dt: number): void;

  /**
   * Что вернуть в мир при сносе — по одной ячейке на элемент.
   *
   * Список, а не число: внутри может лежать и сырьё, и уже готовый продукт,
   * и вернуться обязано именно то, что там лежит. Снос не имеет права ни съесть
   * вещество, ни превратить его во что-то другое.
   */
  abstract drain(): number[];

  abstract get state(): MachineState;
  /** Ход текущей порции, 0..1. Простой — ноль. */
  abstract get progress(): number;

  contains(px: number, py: number): boolean {
    return (
      px >= this.x &&
      px < this.x + this.kind.width &&
      py >= this.y &&
      py < this.y + this.kind.height
    );
  }

  /** Выкладывает корпус в сетку по маске вида. */
  stamp(world: World): void {
    stampKind(world, this.kind, this.x, this.y, this.kind.hull);
  }

  /**
   * Убирает корпус в ПУСТОТУ, а не в породу: здание ничего в мире не создавало
   * и при сносе ничего оставить не должно.
   */
  clear(world: World): void {
    stampKind(world, this.kind, this.x, this.y, MAT.VACUUM);
  }
}

/**
 * Заливает область вида одним материалом по его маске.
 *
 * Одна функция на постановку, снос и постройку без записи в реестре: маска
 * существует ровно затем, чтобы все, кто говорит о корпусе, говорили об одних
 * и тех же ячейках.
 */
export function stampKind(
  world: World,
  kind: BuildingKind,
  x: number,
  y: number,
  material: number,
): void {
  const { width, height, shape } = kind;
  for (let dy = 0; dy < height; dy++) {
    for (let dx = 0; dx < width; dx++) {
      if (shape[dy * width + dx] === 1) world.set(x + dx, y + dy, material);
    }
  }
}

/**
 * Реестр стоящих в мире зданий.
 *
 * Порядок обновления — порядок постановки. Детерминированность нужна та же,
 * что и у автомата, а сортировка по координатам ничего к ней не добавляет:
 * порядок списка уже воспроизводим.
 */
export class BuildingRegistry {
  private readonly list: Building[] = [];

  get all(): readonly Building[] {
    return this.list;
  }

  get count(): number {
    return this.list.length;
  }

  add(building: Building): void {
    this.list.push(building);
  }

  remove(building: Building): void {
    const i = this.list.indexOf(building);
    if (i >= 0) this.list.splice(i, 1);
  }

  /** Здание под точкой мира. Именно им отличается снос от постановки. */
  findAt(x: number, y: number): Building | null {
    for (const b of this.list) {
      if (b.contains(x, y)) return b;
    }
    return null;
  }

  /**
   * Общий шаг: список, а не проход по сетке.
   *
   * Правило внутри автомата означало бы проверку «а не здание ли здесь»
   * на каждой из полумиллиона ячеек мира. Зданий же единицы, и каждое смотрит
   * на два своих ряда.
   */
  update(world: World, dt: number): void {
    for (const b of this.list) b.update(world, dt);
  }
}
