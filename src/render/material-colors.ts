/**
 * Тональные наборы материалов, разложенные на байты, и цвет бегущих роликов
 * конвейера.
 *
 * Данные ПРЕДСТАВЛЕНИЯ, выведенные из таблицы веществ: внутренний цикл рендера
 * читает их на каждый непустой пиксель кадра, и разыменование объекта там
 * заметно дороже. В доменной таблице им делать нечего — она описывает, как
 * вещество себя ведёт, а не каким его показывают.
 *
 * Ограничения набора, которые здесь нельзя нарушить (держит
 * `tests/surface-shading.ts`):
 *
 * 1. Базовые ступени двух материалов не совпадают — по базовой материал
 *    опознаётся. Акценты совпадать МОГУТ: количество материала берётся из
 *    сетки мира, а не подсчётом пикселей, и общий акцент двух пород никому
 *    не мешает.
 * 2. Ни одна ступень не совпадает с площадным цветом задника, со ступенью
 *    интерьера пещеры и с цветом орбитального объекта. Первые два — чтобы
 *    порода не читалась дырой, третье — на уникальности спутника держится
 *    проверка его прохода.
 * 3. Всякая ступень твёрдого материала светлее всякой ступени пещеры.
 */
import { MATERIALS, MAT } from '../world';
import { RAMP } from '../palette';
import { SHADING } from '../config';

const size = MATERIALS.length;
const shades = SHADING.shadesPerMaterial;

/**
 * Акценты материала: ступени темнее и светлее базовой.
 *
 * Отсутствие акцента — не недоделка: материал, который не покрывает площади
 * или считается в кадре поштучно, обязан остаться плоским.
 */
interface ShadeSpec {
  readonly dark?: number;
  readonly light?: number;
}

/**
 * Акценты берутся СОСЕДНИМИ ступенями земляной лестницы, то есть базовыми
 * ступенями соседних пород. Это разрешено намеренно: своей свободной ступени
 * рядом по светлоте в замкнутой палитре нет, а на границе двух пород взаимное
 * проникновение читается переходом слоя — ровно то, чего добивается слоистость
 * в генераторе.
 *
 * У глубинной породы тёмного акцента НЕТ, и это не пропуск. Всякая ступень
 * твёрдого вещества обязана быть светлее интерьера пещеры (`rust[1]`,
 * яркость 42), а `earth[0]` — уже 54; свободной ступени между ними в палитре
 * не осталось. Ближайшие кандидаты заняты площадными поверхностями задника:
 * `violet[0]` (32.5) — заливка слоя, `rust[0]` (27.5) — свечение полосы.
 */
const SHADE_SPEC = new Map<number, ShadeSpec>([
  [MAT.ROCK_DEEP, { light: RAMP.earth[1] }],
  [MAT.ROCK, { dark: RAMP.earth[0], light: RAMP.earth[2] }],
  [MAT.REGOLITH_PACKED, { dark: RAMP.earth[1], light: RAMP.earth[3] }],
  [MAT.REGOLITH_LOOSE, { dark: RAMP.earth[3], light: RAMP.earth[5] }],
]);

/**
 * Цвет ступени: `(материал << shadeBits) | ступень`.
 *
 * Таблица прямоугольная, и материал без акцентов заполняет все ступени базовым
 * цветом. Цикл по пикселям тогда не узнаёт, что материал плоский, и не ветвится.
 *
 * Ступеней восемь, а разных цветов у материала не больше трёх: диапазон нужен
 * широким, чтобы вклады зерна, экспозиции и света складывались без насыщения,
 * а цветов в замкнутой палитре на большее нет.
 */
export const SHADE_R = new Uint8Array(size * shades);
export const SHADE_G = new Uint8Array(size * shades);
export const SHADE_B = new Uint8Array(size * shades);

/** Различные цвета набора материала, от тёмного к светлому. Для проверок. */
export const MAT_SHADES: number[][] = [];

/**
 * Раскладка ступеней: ниже базовой — тёмный акцент, выше — светлый.
 *
 * Базовой отдана РОВНО ОДНА ступень. Отдать ей две — значит поглотить одну
 * сторону зерна: при разбросе в одну ступень сдвиг «светлее» попадал бы обратно
 * в базовый цвет, и зерно умело бы только затемнять. Доминирование базовой
 * держится долей в плитке зерна, а не шириной полосы.
 */
function shadeColor(spec: ShadeSpec, base: number, shade: number): number {
  if (shade < SHADING.baseShade) return spec.dark ?? base;
  if (shade === SHADING.baseShade) return base;
  return spec.light ?? base;
}

for (const m of MATERIALS) {
  const spec = SHADE_SPEC.get(m.id) ?? {};
  const distinct: number[] = [];

  for (let s = 0; s < shades; s++) {
    const color = shadeColor(spec, m.color, s);
    const at = (m.id << SHADING.shadeBits) | s;
    SHADE_R[at] = (color >> 16) & 0xff;
    SHADE_G[at] = (color >> 8) & 0xff;
    SHADE_B[at] = color & 0xff;
    if (!distinct.includes(color)) distinct.push(color);
  }

  MAT_SHADES[m.id] = distinct;
}

/**
 * Цвет бегущих роликов конвейера. Не поле таблицы: в мире роликов нет — ячейка
 * хранит идентификатор ленты, ролики рисует рендер.
 *
 * Инвариант: ступень занята роликами ИСКЛЮЧИТЕЛЬНО — по ней считают пиксели,
 * чтобы увидеть, что лента идёт, и любой сосед по цвету подмешался бы в счёт
 * молча. Отсюда же плоскость самой ленты: у конвейера нет акцентов, иначе
 * счёт «ролик плюс корпус равен секции» перестал бы сходиться.
 * Держит `tests/conveyor.ts`.
 *
 * Ступень 7 против ступени 5 у корпуса: две ступени лестницы — наименьший
 * разрыв, на котором ролик виден и не спорит с корпусом за внимание.
 */
export const CONVEYOR_ROLLER_COLOR = RAMP.gray[7];
