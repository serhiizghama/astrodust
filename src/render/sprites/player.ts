import { PLAYER } from '../../config';
import { RAMP } from '../../palette';
import { parseSprite } from '../draw';

/**
 * Спрайт космонавта 8x12 прямо в коде: ассет-пайплайн на этом этапе — чистые
 * накладные расходы, а правка пикселя здесь видна в git-дифе.
 *
 * Индексы палитры: 0 — прозрачно, 1 — светлый скафандр, 2 — тень/ранец,
 * 3 — визор, 4 — тёмный контур.
 */
const SPRITE_ROWS = [
  '..4444..',
  '.411114.',
  '.413331.',
  '.413331.',
  '..4114..',
  '.411114.',
  '.421114.',
  '.421114.',
  '.411114.',
  '..4114..',
  '..1441..',
  '..4..4..',
];

/**
 * Инвариант контура: темнее пещеры (41.8) и светлее неба (10.7) одновременно —
 * иначе силуэт пропадает либо под землёй, либо в полёте на ранце. `gray[2]`
 * (27.7) держит обе границы; самый тёмный `gray[0]` совпал бы с небом.
 *
 * Инвариант ранца: НЕ `gray[7]` — это цвет бегущей полосы конвейера, а полосу
 * считают пиксель в пиксель, и два пикселя ранца подмешивались бы в счёт.
 */
export const SPRITE_PALETTE = [
  RAMP.gray[0], // 0 — прозрачно, рендером не читается
  RAMP.gray[9], // 1 — светлый скафандр
  RAMP.gray[6], // 2 — тень и ранец
  RAMP.blue[4], // 3 — визор
  RAMP.gray[2], // 4 — тёмный контур
];

export const SPRITE_W = 8;
export const SPRITE_H = 12;

export const SPRITE_PIXELS = parseSprite(SPRITE_ROWS, SPRITE_W);

/** Смещение спрайта относительно левого верхнего угла хитбокса. */
export const SPRITE_OFFSET_X = -(SPRITE_W - PLAYER.hitboxW) / 2; // -1
export const SPRITE_OFFSET_Y = -(SPRITE_H - PLAYER.hitboxH); // -2, шлем торчит вверх
