/**
 * Упорядоченный дизеринг — единственный способ показать промежуточный тон.
 *
 * Палитра замкнута: смешивать, затемнять и интерполировать цвета нельзя,
 * промежуточный оттенок — это выход за набор. Плавность выражается
 * чередованием пикселей двух соседних ступеней по этой матрице.
 *
 * Матрица объявлена ЗДЕСЬ, а не по месту использования. Задник и тонирование
 * поверхностей рисуют смежные области кадра, и две копии матрицы — даже
 * побайтово одинаковые — разошлись бы при первой же правке одной из них,
 * а шов между небом и породой стал бы виден.
 */

/** Сторона матрицы. Степень двойки: индекс берётся маской, а не делением. */
export const DITHER_SIZE = 4;

/** Маска для взятия координаты по модулю стороны. */
export const DITHER_MASK = DITHER_SIZE - 1;

/** Число уровней матрицы: порог сравнивается с долей в этой шкале. */
export const DITHER_LEVELS = DITHER_SIZE * DITHER_SIZE;

/**
 * Порядок Байера 4×4, значения 0..15.
 *
 * Инвариант: это перестановка чисел 0..15 без повторов. Повтор означал бы,
 * что две позиции плитки переключаются на одном пороге, и градиент пошёл бы
 * ступеньками вместо равномерного заполнения. Держит `tests/surface-shading.ts`.
 */
export const BAYER = [0, 8, 2, 10, 12, 4, 14, 6, 3, 11, 1, 9, 15, 7, 13, 5];

/**
 * Порог плитки в точке (x, y) — доля в [0, 1).
 *
 * Сравнение `threshold(x, y) < intensity` даёт долю закрашенных пикселей,
 * равную `intensity`, распределённую по плитке равномерно.
 */
export function threshold(x: number, y: number): number {
  return BAYER[((y & DITHER_MASK) << 2) | (x & DITHER_MASK)]! / DITHER_LEVELS;
}
