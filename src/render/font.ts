/**
 * Символ без глифа. Видимая коробка, а не пропуск: пропуск превращает
 * недостающую букву в опечатку, которую никто не заметит.
 */
const FALLBACK_ROWS = ['....', '####', '#..#', '#..#', '#..#', '####', '....'];

interface Glyph {
  readonly w: number;
  /** Маска занятых столбцов на каждую из семи строк: бит `i` — столбец `i`. */
  readonly rows: Uint8Array;
}

function compile(rows: readonly string[]): Glyph {
  const mask = new Uint8Array(GLYPH_H);
  let w = 0;
  for (let y = 0; y < GLYPH_H; y++) {
    const row = rows[y] ?? '';
    let bits = 0;
    for (let x = 0; x < row.length; x++) {
      if (row[x] !== '#') continue;
      bits |= 1 << x;
      if (x + 1 > w) w = x + 1;
    }
    mask[y] = bits;
  }
  return { w, rows: mask };
}

const GLYPHS = new Map<string, Glyph>();
for (const [ch, rows] of Object.entries(GLYPH_ROWS)) GLYPHS.set(ch, compile(rows));
// Пробел занятых столбцов не имеет, и ширина из данных вышла бы нулевой.
GLYPHS.set(' ', { w: SPACE_W, rows: new Uint8Array(GLYPH_H) });

const FALLBACK = compile(FALLBACK_ROWS);

/** Есть ли в шрифте глиф этого символа. Нужен проверке полноты набора. */
export function hasGlyph(ch: string): boolean {
  return GLYPHS.has(ch);
}

/** Все символы, набранные в шрифте. */
export function glyphChars(): string[] {
  return [...GLYPHS.keys()];
}

/**
 * Ширина строки в пикселях. Складывает те же числа, что кладёт `drawText`,
 * поэтому раскладка по правому краю и центрирование не могут промахнуться.
 *
 * Просвет после последнего глифа в ширину НЕ входит: иначе строка, прижатая
 * к правому краю, отступала бы от него на пиксель.
 */
export function textWidth(s: string): number {
  let w = 0;
  for (const ch of s) w += (GLYPHS.get(ch) ?? FALLBACK).w + GLYPH_GAP;
  return w > 0 ? w - GLYPH_GAP : 0;
}

/**
 * Строка в буфер кадра. `x`, `y` — левый верхний угол коробки первого глифа.
 *
 * Подложка выводится ОТДЕЛЬНЫМ проходом по всей строке, а не под каждой буквой
 * по очереди: иначе тень следующего глифа ложится поверх предыдущего и съедает
 * его правый столбец.
 *
 * @param shadow подложка в один пиксель по диагонали. Выключается для текста
 *   на собственной непрозрачной подложке панели — там контраст обеспечен фоном.
 */
export function drawText(
  px: Uint8ClampedArray,
  w: number,
  h: number,
  s: string,
  x: number,
  y: number,
  color: number,
  shadow = true,
): void {
  if (shadow) stamp(px, w, h, s, x + 1, y + 1, TEXT_SHADOW);
  stamp(px, w, h, s, x, y, color);
}

function stamp(
  px: Uint8ClampedArray,
  w: number,
  h: number,
  s: string,
  x: number,
  y: number,
  color: number,
): void {
  let at = x;
  for (const ch of s) {
    const glyph = GLYPHS.get(ch) ?? FALLBACK;
    for (let gy = 0; gy < GLYPH_H; gy++) {
      const bits = glyph.rows[gy]!;
      if (bits === 0) continue;
      for (let gx = 0; gx < glyph.w; gx++) {
        if (bits & (1 << gx)) setPixel(px, w, h, at + gx, y + gy, color);
      }
    }
    at += glyph.w + GLYPH_GAP;
  }
}
