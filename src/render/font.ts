/**
 * Растровый шрифт интерфейса: единственный способ вывести текст в игре.
 *
 * Глифы набраны строками `#`/`.` прямо в исходнике, а не битовыми масками:
 * правка буквы обязана быть видна в дифе буквой. Их около двух сотен, и без
 * этого их не довести до приемлемого вида.
 *
 * Коробка глифа — 7 строк, до 5 столбцов. Полосы фиксированы, и глиф,
 * нарисованный не в своей полосе, встанет выше или ниже соседей:
 *
 *   строка 0 — надстрочные знаки заглавных (`Ё`, `Й`);
 *   строки 1–5 — заглавные, цифры, знаки, выносные элементы строчных;
 *   строки 2–5 — рост строчной буквы;
 *   строка 6 — подстрочные хвосты (`р`, `у`, `Ц`, `Щ`, `Д`).
 *
 * Ширина глифа выводится ИЗ ДАННЫХ — номер последнего занятого столбца плюс
 * один, — поэтому `textWidth` и `drawText` не могут разойтись: они складывают
 * одни и те же числа. Шаг между глифами — ширина плюс `GLYPH_GAP`.
 *
 * Полноту набора относительно текстов игры держит `tests/pixel-text.ts`.
 */
