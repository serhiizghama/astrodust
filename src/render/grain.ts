/**
 * Зерно поверхности: неоднородность породы в пределах одного вещества.
 *
 * Плитка сдвигов ступени, посчитанная один раз при загрузке. В кадре — одно
 * чтение на пиксель. Считать хеш координаты на месте нельзя: это три `Math.imul`
 * на каждый непустой пиксель кадра, а требование бюджета прямо запрещает
 * вычисления на пиксель.
 *
 * Плитка индексируется МИРОВОЙ координатой, а не экранной. От экранной зерно
 * плыло бы по породе при каждом сдвиге камеры: неподвижная стена выглядела бы
 * текущей.
 */
import { SHADING } from '../config';
import { mulberry32 } from '../world';

const SIZE = SHADING.grainTile;

/**
 * Сдвиги ступени: `baseShade + GRAIN[...]`. Значения смещены на `baseShade`,
 * чтобы в кадре складывать без второго слагаемого.
 *
 * Инвариант: базовая ступень доминирует. Ниже половины порода теряет
 * опознаваемый цвет и читается шумом; доля задаётся `grainBaseShare`, а
 * следствие в кадре держит `tests/surface-shading.ts` — «базовая ступень
 * занимает больше половины пикселей сплошной породы на глубине».
 */
export const GRAIN = new Uint8Array(SIZE * SIZE);

{
  // Зерно от собственного зерна ГПСЧ, не от мирового: плитка — свойство
  // отрисовки, и менять рисунок породы вместе со сменой уровня незачем.
  const rand = mulberry32(0x9e3779b9);
  const amp = SHADING.grainAmplitude;
  const share = SHADING.grainBaseShare;
  // Остаток делится поровну между «темнее» и «светлее»: смещение в одну
  // сторону сдвинуло бы среднюю яркость породы и разошлось бы с её базовым
  // цветом в таблице веществ.
  const side = (1 - share) / 2;

  /**
   * Решение принимается на СДВОЕННОЙ клетке, а потом растягивается на 2×2.
   *
   * Независимый выбор на пиксель даёт равномерную рябь — она читается
   * помехами приёма, а не породой: у настоящей породы вкрапления сбиты
   * в зёрна, а не рассыпаны по одному. Растяжение вдвое стоит ноль в кадре
   * (плитка считается один раз) и превращает рябь в зерно.
   */
  const coarse = SIZE >> 1;
  for (let cy = 0; cy < coarse; cy++) {
    for (let cx = 0; cx < coarse; cx++) {
      const r = rand();
      let step = 0;
      if (r < side) step = -amp;
      else if (r >= side + share) step = amp;
      const value = SHADING.baseShade + step;

      const x0 = cx << 1;
      const y0 = cy << 1;
      GRAIN[y0 * SIZE + x0] = value;
      GRAIN[y0 * SIZE + x0 + 1] = value;
      GRAIN[(y0 + 1) * SIZE + x0] = value;
      GRAIN[(y0 + 1) * SIZE + x0 + 1] = value;
    }
  }
}
